"""Generate include/recomp.h: N64Recomp's recomp.h with a software TLB in every memory access.

Mario Tennis maps game data through the TLB (e.g. segment 2 at 0x02000000) and dereferences those
virtual addresses on the CPU. The recompiled code therefore translates addresses below KSEG0 via a
4 KiB page table filled by osMapTLB (src/game/mt_tlb.cpp), and folds KSEG1 onto KSEG0. KSEG0, the
common case, stays a single compare. include/ precedes the runtime's include dirs, so only the game
code and the Mario Tennis glue see this header; the runtime keeps the original."""
import re, sys
src = "lib/N64ModernRuntime/N64Recomp/include/recomp.h"
s = open(src).read()
n = s.count("- 0xFFFFFFFF80000000")
assert n == 7, f"unexpected recomp.h layout ({n} address sites); re-check before regenerating"

xlat = '''
// ---- Mario Tennis: software TLB (generated by tools/make_recomp_h.py) ----
#ifdef __cplusplus
extern "C" {
#endif
gpr mt_xlat_slow(gpr address);
#ifdef __cplusplus
}
#endif
static inline gpr mt_xlat(gpr address) {
    uint32_t a = (uint32_t)address;
    if (__builtin_expect((a & 0xE0000000u) == 0x80000000u, 1)) {
        return address;
    }
    return mt_xlat_slow(address);
}
#define MT_XLAT(addr) mt_xlat((gpr)(addr))
// Function-pointer variant: same translation, but routed through mt_xlat_func_slow (mt_tlb.cpp) so
// calls into TLB-mapped code can be logged.
#ifdef __cplusplus
extern "C"
#endif
gpr mt_xlat_func_slow(gpr address);
static inline gpr mt_xlat_func(gpr address) {
    if (__builtin_expect(((uint32_t)address & 0xE0000000u) == 0x80000000u, 1)) {
        return address;
    }
    return mt_xlat_func_slow(address);
}
// ---- end software TLB ----
'''
s = s.replace("typedef uint64_t gpr;\n", "typedef uint64_t gpr;\n" + xlat, 1)
s = s.replace("rdram + ((((reg) + (offset))) - 0xFFFFFFFF80000000)", "rdram + ((MT_XLAT((reg) + (offset))) - 0xFFFFFFFF80000000)")
s = s.replace("rdram + ((((reg) + (offset)) ^ 2) - 0xFFFFFFFF80000000)", "rdram + ((MT_XLAT((reg) + (offset)) ^ 2) - 0xFFFFFFFF80000000)")
s = s.replace("rdram + ((((reg) + (offset)) ^ 3) - 0xFFFFFFFF80000000)", "rdram + ((MT_XLAT((reg) + (offset)) ^ 3) - 0xFFFFFFFF80000000)")
s = s.replace("rdram + ((((reg) + (offset) + 4)) - 0xFFFFFFFF80000000)", "rdram + ((MT_XLAT((reg) + (offset) + 4)) - 0xFFFFFFFF80000000)")
s = s.replace("rdram + ((((reg) + (offset) + 0)) - 0xFFFFFFFF80000000)", "rdram + ((MT_XLAT((reg) + (offset) + 0)) - 0xFFFFFFFF80000000)")
assert s.count("MT_XLAT((reg)") == 7, "not every access site was rewritten"
# Function pointers into TLB-mapped code (e.g. a sliding window over a code module) are translated
# to their physical (KSEG0) address too; TLB modules are registered at the buffer they occupy.
old_lookup = "get_function((int32_t)(val))"
assert s.count(old_lookup) == 1, "unexpected LOOKUP_FUNC definition"
s = s.replace(old_lookup, "get_function((int32_t)mt_xlat_func((gpr)(val)))")
open("include/recomp.h", "w").write("// GENERATED from " + src + " by tools/make_recomp_h.py -- do not edit.\n" + s)
print("include/recomp.h written (7 access sites translated)")
