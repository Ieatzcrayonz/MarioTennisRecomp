"""Find tight polling loops (busy-waits) in the recompiled sections.

The runtime schedules game threads cooperatively: a thread that spins on memory never lets the
runtime deliver SP/DP/VI events, so the value it waits for never changes. A spin here is a
backward branch over at most MAX_LEN instructions whose body only loads, compares and branches
(no calls, no stores, no other control flow). Each one gets a yield hook at its loop head.

Prints (function, loop head vram, polled address if known) and writes them as N64Recomp hooks
between the SPIN-HOOKS markers in mt.us.toml."""
import re, struct, sys
sys.path.insert(0, __file__.replace("\\", "/").rsplit("/", 1)[0])
from find_funcs import _branch_target

MAX_LEN = 6
LOADS = {0x20, 0x21, 0x23, 0x24, 0x25, 0x27, 0x31, 0x35, 0x37}
ALU_I = {0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F}

img = open("build_assets/mt.us.recomp.z64", "rb").read()
syms = open("syms/mt.us.syms.toml").read()
base_cfg = open("mt.us.toml").read()
ignored = set(re.findall(r'"(func_\w+)"', base_cfg.split("ignored = [")[1].split("]")[0]))

spins = []
for sec in re.split(r"\[\[section\]\]", syms)[1:]:
    rom = int(re.search(r"rom = 0x(\w+)", sec).group(1), 16)
    vram = int(re.search(r"\nvram = 0x(\w+)", sec).group(1), 16)
    for fn, v, sz in re.findall(r'name = "(\w+)", vram = 0x(\w+), size = 0x(\w+)', sec):
        if fn in ignored or not fn.startswith("func_"): continue
        v = int(v, 16); sz = int(sz, 16)
        W = [struct.unpack(">I", img[rom + v - vram + 4*k: rom + v - vram + 4*k + 4])[0] for k in range(sz // 4)]
        for i, w in enumerate(W):
            t = _branch_target(w, i)
            if t is None or not (0 <= t < i) or i - t > MAX_LEN: continue
            body = W[t:i] + ([W[i + 1]] if i + 1 < len(W) else [])
            ok = True; polled = None; hi = {}
            for b in body:
                op = b >> 26
                if b == 0: continue
                if op == 0x0F: hi[(b >> 16) & 31] = (b & 0xFFFF) << 16; continue
                if op in LOADS:
                    rs = (b >> 21) & 31; imm = b & 0xFFFF
                    if rs in hi: polled = (hi[rs] + (imm - 0x10000 if imm & 0x8000 else imm)) & 0xFFFFFFFF
                    continue
                if op in ALU_I or (op == 0 and (b & 0x3F) in (0x20, 0x21, 0x23, 0x24, 0x25, 0x26, 0x27, 0x2A, 0x2B, 0x00, 0x02, 0x03)):
                    continue
                if op in (0x01, 0x04, 0x05, 0x06, 0x07, 0x14, 0x15, 0x16, 0x17) and b is not w and _branch_target(b, 0) is not None:
                    ok = False; break
                if op in (0x01, 0x04, 0x05, 0x06, 0x07, 0x14, 0x15, 0x16, 0x17):
                    continue
                ok = False; break   # call, store, jump or anything with side effects
            # A busy-wait re-reads the same address: no instruction in the loop may write a register
            # that a load uses as its base (that would be a search/walk loop, which terminates).
            if ok:
                bases = {(b >> 21) & 31 for b in body if (b >> 26) in LOADS}
                written = set()
                for b in body:
                    op = b >> 26
                    if op == 0 and b != 0: written.add((b >> 11) & 31)
                    elif op in ALU_I or op in LOADS: written.add((b >> 16) & 31)
                lui_regs = {(b >> 16) & 31 for b in body if (b >> 26) == 0x0F}
                if bases & (written - lui_regs):
                    ok = False
            if ok and any((b >> 26) in LOADS for b in body):
                hook_fn = "recomp_entrypoint" if v == 0x80031000 else fn
                spins.append((hook_fn, v + 4*t, polled))

for fn, head, polled in spins:
    print(f"{fn:30} loop at {head:08X}  polls {polled:08X}" if polled else f"{fn:30} loop at {head:08X}")
print(len(spins), "spin loops")

hooks = ["# SPIN-HOOKS BEGIN (generated by tools/find_spins.py -- do not edit by hand)\n",
         "# Busy-waits yield to the cooperative scheduler so SP/DP/VI events can be delivered.\n"]
for fn, head, polled in spins:
    note = f" # polls 0x{polled:08X}" if polled else ""
    hooks.append(f'[[patches.hook]]{note}\nfunc = "{fn}"\nbefore_vram = 0x{head:08X}\n'
                 f'text = "    {{ void mt_spin_yield(uint8_t* rdram, uint32_t id); mt_spin_yield(rdram, 0); }}"\n\n')
hooks.append("# SPIN-HOOKS END\n")
block = "".join(hooks)
if "# SPIN-HOOKS BEGIN" in base_cfg:
    base_cfg = re.sub(r"# SPIN-HOOKS BEGIN.*?# SPIN-HOOKS END\n", lambda m: block, base_cfg, flags=re.S)
else:
    base_cfg = base_cfg.rstrip("\n") + "\n\n" + block
open("mt.us.toml", "w").write(base_cfg)
