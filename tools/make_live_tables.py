"""Generates src/game/mt_live_data.inc: the tables the exe needs to recompile the game's code from the
player's own ROM at startup (src/game/mt_live.cpp).

Everything here is our own data: section and function addresses/sizes and names (syms/), the TLB
section's relocations, the segment map, and our patches and hooks from mt.us.toml. No game code or
data is copied. Hooks are emitted as C bodies in an event dispatcher, so they run the same code as the
offline build's inserted text.

Usage: python tools/make_live_tables.py   (rerun after gen_symbols.py / find_spins.py / editing mt.us.toml)
"""
import json, os, re, sys, tomllib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N64RECOMP = os.path.join(ROOT, "lib", "N64ModernRuntime", "N64Recomp")


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def name_set(text, set_name):
    m = re.search(r"N64Recomp::" + set_name + r"\s*\{(.*?)\};", text, re.S)
    return set(re.findall(r'"([^"]+)"', m.group(1)))


def main():
    syms = tomllib.load(open(os.path.join(ROOT, "syms", "mt.us.syms.toml"), "rb"))
    cfg = tomllib.load(open(os.path.join(ROOT, "mt.us.toml"), "rb"))
    overlay_map = json.load(open(os.path.join(ROOT, "syms", "overlay_map.json")))
    lists = open(os.path.join(N64RECOMP, "src", "symbol_lists.cpp")).read()
    reimpl, builtin_ignored = name_set(lists, "reimplemented_funcs"), name_set(lists, "ignored_funcs")

    patches = cfg.get("patches", {})
    own_ignored = patches.get("ignored", [])
    all_names = {f["name"] for s in syms["section"] for f in s["functions"]}

    # Natives the game calls instead of recompiled code: the runtime's libultra replacements
    # (<name>_recomp) and our own replacements in mt_libultra.cpp (same name).
    natives = sorted(n for n in all_names if n in reimpl)
    # Built-in ignored libultra internals only need a native if the game actually calls them; the
    # offline build's output tells us which ones it referenced (all others never link).
    called = set()
    funcs_dir = os.path.join(ROOT, "RecompiledFuncs")
    if os.path.isdir(funcs_dir):
        for fn in os.listdir(funcs_dir):
            if fn.endswith(".c"):
                called |= set(re.findall(r"\b([A-Za-z_]\w*)_recomp\(rdram", open(os.path.join(funcs_dir, fn)).read()))
    natives += sorted(n for n in all_names if n in builtin_ignored and n in called and n not in reimpl)

    out = ["// Generated by tools/make_live_tables.py -- do not edit by hand.",
           "// Addresses, names and patches only (our own data); the code itself comes from the player's ROM.", ""]

    out.append("static const MtLiveSegment mt_live_segments[] = {")
    for e in overlay_map:
        out.append(f"    {{ 0x{e['real_rom']:08X}, 0x{e['vrom']:08X} }},")
    out.append("};\n")

    out.append("static const MtLiveFunc mt_live_funcs[] = {")
    sec_lines = []
    reloc_lines = []
    for si, s in enumerate(syms["section"]):
        first = sum(len(x["functions"]) for x in syms["section"][:si])
        relocs = s.get("relocs")
        rfirst = len(reloc_lines)
        for r in relocs or []:
            reloc_lines.append(f"    {{ 0x{r['vram']:08X}, 0x{r['target_vram']:08X}, {cstr(r['type'])} }},")
        sec_lines.append(f"    {{ {cstr(s['name'])}, 0x{s['rom']:08X}, 0x{s['vram']:08X}, 0x{s['size']:08X}, {first}, {len(s['functions'])}, "
                         f"{'true' if relocs is not None else 'false'}, {rfirst}, {len(relocs or [])} }},")
        for f in s["functions"]:
            out.append(f"    {{ {cstr(f['name'])}, 0x{f['vram']:08X}, 0x{f['size']:X} }},")
    out.append("};\n")
    out.append("static const MtLiveSection mt_live_sections[] = {")
    out += sec_lines
    out.append("};\n")
    out.append("static const MtLiveReloc mt_live_relocs[] = {")
    out += reloc_lines or ["    { 0, 0, nullptr },"]
    out.append("};\n")

    out.append("static const char* const mt_live_ignored[] = {")
    out += [f"    {cstr(n)}," for n in own_ignored] or ["    nullptr,"]
    out.append("};\n")

    out.append("static const MtLivePatch mt_live_patches[] = {")
    for p in patches.get("instruction", []):
        out.append(f"    {{ {cstr(p['func'])}, 0x{p['vram']:08X}, 0x{p['value']:08X} }},")
    out.append("};\n")

    hooks = patches.get("hook", [])
    out.append("static const MtLiveHook mt_live_hooks[] = {")
    for i, h in enumerate(hooks):
        out.append(f"    {{ {cstr(h['func'])}, 0x{h.get('before_vram', 0):08X} }}, // event {i}")
    out.append("};\n")

    out.append("// Native implementations, by the name the game's symbol has.")
    decls = []
    table = []
    for n in natives:
        sym = n + "_recomp"
        decls.append(f'extern "C" void {sym}(uint8_t* rdram, recomp_context* ctx);')
        table.append(f"    {{ {cstr(n)}, {sym} }},")
    # Our own replacements: only the ones src/ defines (others are simply never called).
    src_text = "".join(open(os.path.join(dp, f), errors="ignore").read()
                       for dp, _, fs in os.walk(os.path.join(ROOT, "src")) for f in fs if f.endswith(".cpp"))
    for n in own_ignored:
        if not re.search(r'extern "C"\s+void\s+' + re.escape(n) + r"\(", src_text):
            continue
        decls.append(f'extern "C" void {n}(uint8_t* rdram, recomp_context* ctx);')
        table.append(f"    {{ {cstr(n)}, {n} }},")
    out += decls
    out.append("static const MtLiveNative mt_live_natives[] = {")
    out += table
    out.append("};\n")

    out.append("// Hook bodies (the same text the offline build inserts), run by the live code's event calls.")
    out.append('extern "C" { // hook texts declare C functions')
    out.append("static void mt_live_run_hook(uint8_t* rdram, recomp_context* ctx, uint32_t index) {")
    out.append("    switch (index) {")
    for i, h in enumerate(hooks):
        out.append(f"        case {i}: {h['text'].strip()} break;")
    out.append("    }")
    out.append("}")
    out.append("}")

    path = os.path.join(ROOT, "src", "game", "mt_live_data.inc")
    open(path, "w", newline="\n").write("\n".join(out) + "\n")
    print(f"{path}: {sum(len(s['functions']) for s in syms['section'])} functions, {len(syms['section'])} sections, "
          f"{len(reloc_lines)} relocs, {len(natives) + len(own_ignored)} natives, {len(hooks)} hooks")


if __name__ == "__main__":
    main()
